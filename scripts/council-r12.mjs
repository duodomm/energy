async function main() {
  const zai = await ZAI.create()
  const prev = []

  for (const it of ITERATIONS) {
    const file = path.join(OUT_DIR, `out-${it.n}.md`)
    if (fs.existsSync(file) && fs.statSync(file).size > 500) {
      console.log(`И${it.n}: уже есть, пропускаю`)
      prev.push(fs.readFileSync(file, 'utf-8'))
      continue
    }
    const extra = it.n === 10
      ? `\n\nВЫЖИМКИ ПРЕДЫДУЩИХ ИТЕРАЦИЙ (консолидируй именно их):\n${prev.map((p, i) => `--- И${i + 1} ---\n${p.slice(0, 900)}`).join('\n')}`
      : ''

    const prompt = `ТЕМА ИТЕРАЦИИ №${it.n}: «${it.topic}»\n\nФОКУС: ${it.focus}\n\n${FACTS}${extra}`

    for (let attempt = 1; attempt <= 2; attempt++) {
      try {
        const r = await zai.chat.completions.create({
          messages: [
            { role: 'system', content: MANDATE },
            { role: 'user', content: prompt },
          ],
          thinking: { type: 'disabled' },
        })
        const text = r.choices[0]?.message?.content ?? ''
        if (text.length < 400) throw new Error('слишком короткий ответ')
        fs.writeFileSync(file, `# И${it.n}: ${it.topic}\n\n${text}\n`)
        console.log(`И${it.n}: OK (${(text.length / 1024).toFixed(1)} КБ)`)
        prev.push(text)
        break
      } catch (e) {
        console.log(`И${it.n}: попытка ${attempt} не удалась — ${e.message}`)
        if (attempt === 2) {
          fs.writeFileSync(file, `# И${it.n}: ${it.topic}\n\n(итерация не удалась: ${e.message})\n`)
        } else {
          await new Promise(r => setTimeout(r, 2000))
        }
      }
    }
  }
  console.log('DONE')
}

main().catch(e => { console.error('FATAL', e); process.exit(1) })
